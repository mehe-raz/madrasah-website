create unique index if not exists students_admission_number_unique
on students ("admissionNumber")
where "admissionNumber" is not null and "admissionNumber" <> '';

create unique index if not exists students_birth_registration_unique
on students ("birthRegistrationNumber")
where "birthRegistrationNumber" is not null and "birthRegistrationNumber" <> '';

create table if not exists attendance (
  id integer generated by default as identity primary key,
  "studentId" integer not null references students(id) on delete cascade,
  date text not null,
  status text not null,
  unique ("studentId", date)
);

create table if not exists payments (
  id integer generated by default as identity primary key,
  "studentId" integer not null references students(id) on delete cascade,
  student text not null,
  roll text not null,
  amount integer not null,
  date text not null,
  receipt text not null,
  method text default 'Cash',
  status text default 'Completed'
);

create unique index if not exists payments_receipt_unique on payments (receipt);

create table if not exists income (
  id integer generated by default as identity primary key,
  category text not null,
  amount integer not null,
  date text not null,
  note text default '',
  method text default 'Cash',
  receipt text not null,
  "studentId" integer references students(id) on delete set null,
  status text default 'Completed'
);

create unique index if not exists income_receipt_unique on income (receipt);

