-- Retroactive fix (2026-08): routes/attendance.js's POST / does a bulk
-- upsert with `ON CONFLICT ("studentId", date) DO UPDATE ...`, which
-- requires a unique index/constraint covering exactly those two columns to
-- exist — Postgres matches ON CONFLICT by column list, not by name. The
-- inline `unique ("studentId", date)` above only ever runs on a BRAND NEW
-- database (the CREATE TABLE itself is a no-op once the table already
-- exists, same caveat as the payments/income fixes above). Any institution
-- whose `attendance` table was created before that inline constraint was
-- added never got it, so every attendance save on that database hit
-- Postgres error 42P10 ("no unique or exclusion constraint matching the ON
-- CONFLICT specification") — an uncaught 500, attendance never saved. A
-- separate unique INDEX (not a same-named constraint, since the original's
-- auto-generated name isn't reliably known) satisfies ON CONFLICT just as
-- well and is safe to add unconditionally: `if not exists` makes it a
-- no-op on databases that already have this covered.
create unique index if not exists attendance_student_date_unique
on attendance ("studentId", date);

