-- ============================================================
-- Guardian Push Notifications (docs/PUSH_NOTIFICATION_PLAN.md — Phase 1)
-- ============================================================
-- One row per subscribed browser/device per guardian (a guardian logged in
-- on both their phone and a desktop browser gets two rows, both receive a
-- push). "endpoint" is the browser's own unique per-subscription push URL
-- — used as the natural upsert key so re-subscribing the same
-- browser/device (e.g. after clearing site data) updates the existing row
-- instead of accumulating duplicates. "p256dh"/"auth" are the
-- browser-generated encryption keys the Web Push spec requires to encrypt
-- the payload — meaningless without the matching VAPID private key
-- (server/src/lib/guardianPush.js, Phase 2), so no additional encryption
-- is needed on this table itself. A subscription is deleted outright (not
-- soft-deleted/deactivated) either when the guardian explicitly
-- unsubscribes or when a push attempt gets back 404/410 Gone from the
-- push service (guardianPush.js's own cleanup, not here) — there is no
-- reason to keep a dead subscription row around.
create table if not exists guardian_push_subscriptions (
  id integer generated by default as identity primary key,
  "guardianId" integer not null references guardian_accounts(id) on delete cascade,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  "userAgent" text,
  "createdAt" text not null
);

create index if not exists guardian_push_subscriptions_guardian_idx on guardian_push_subscriptions ("guardianId");

-- Same idea as guardian_push_subscriptions above, but for staff/admin
-- accounts (users table) instead of guardian_accounts — used to alert
-- Super Admin's own browser/phone the moment an automatic backup fails or
-- can't reach Google Drive (lib/adminPush.js), since that failure would
-- otherwise only ever surface if someone happens to open Settings and look.
-- Shares the same VAPID keypair/env vars as guardian push (Web Push
-- doesn't require a separate keypair per audience).
create table if not exists admin_push_subscriptions (
  id integer generated by default as identity primary key,
  "userId" integer not null references users(id) on delete cascade,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  "userAgent" text,
  "createdAt" text not null
);

create index if not exists admin_push_subscriptions_user_idx on admin_push_subscriptions ("userId");

-- ============================================================
-- BUSINESS_READINESS_ROADMAP.md Phase 8A — SMS wallet + ledger
-- ============================================================
-- Schema-per-tenant means this table lives inside one institution's own
-- schema (search_path-scoped, same as every other table above) — so unlike
-- a shared multi-tenant table, it does NOT need an "institutionId" column
-- to separate rows between institutions. Each tenant schema, and the
-- single-tenant `public` schema, gets exactly one wallet row: application
-- code (smsSender.js, Phase 8B) always reads/updates that one row rather
-- than looking one up by institution. The row itself is inserted once, at
-- provisioning time (tenantProvision.js for a new tenant; db.js's initDb()
-- for a single-tenant deployment) — this CREATE TABLE only defines the
-- shape, same convention as `settings` (a table this file never seeds
-- rows into either).
create table if not exists sms_wallets (
  id integer generated by default as identity primary key,
  balance_taka numeric(12,2) not null default 0,
  "updatedAt" timestamptz not null default now()
);

-- Ledger of every wallet change (type: 'topup' | 'deduct'). smsCount is
-- null for a topup row (money added, no SMS sent yet) and set for a deduct
-- row (how many SMS that deduction paid for). reference is free text —
-- e.g. a manual top-up's bKash Trx ID (8D), or the SMS provider's own
-- message/batch id (8B) — kept as a string since the two sources have
-- unrelated id formats. createdAt is text (ISO string), matching every
-- other ledger/log table in this file (audit_logs, notifications,
-- admissions) rather than the timestamptz style used for point-in-time
-- fields like sms_wallets."updatedAt" above.
create table if not exists sms_transactions (
  id integer generated by default as identity primary key,
  type text not null,
  "amountTaka" numeric(12,2) not null,
  "smsCount" integer,
  reference text default '',
  "createdAt" text not null
);

-- BUSINESS_READINESS_ROADMAP.md Phase 8D — manual top-up requests. An
-- institution-admin submits a bKash Trx ID (type='topup', status='pending'
-- row, balance NOT touched yet); a platform Super-Admin checks the real
-- bKash inbox and approves/rejects from the platform panel
-- (routes/platform.js, tenant-scoped via migrateTenants.withTenantSchema).
-- Only approval credits sms_wallets.balance_taka. Every row inserted
-- before this phase (Phase 8B's deduct rows) has no explicit status, so
-- the default keeps them correctly classified as already-settled/
-- "confirmed" rather than retroactively looking "pending".
alter table sms_transactions add column if not exists "status" text not null default 'confirmed';

create index if not exists sms_transactions_created_at_idx on sms_transactions ("createdAt" desc);

-- ============================================================
-- BUSINESS_READINESS_ROADMAP.md Phase 8E — bKash self-connect
-- ============================================================
-- One row per institution's own bKash agent/merchant credentials
-- (Bring-Your-Own-Account — see roadmap Phase 8 intro). Schema-per-tenant
-- means this table lives inside one institution's own schema, same as
-- sms_wallets above, so it needs no institutionId column either — at most
-- one row ever exists here, upserted by routes/paymentGateway.js.
-- Credentials are NEVER stored in plaintext: appKey/appSecret/username/
-- password are each encrypted with lib/gatewayCredentialCrypto.js
-- (AES-256-GCM, same algorithm as lib/backupEncryption.js but for short
-- strings instead of files, keyed by the separate GATEWAY_CREDENTIAL_KEY
-- env var so a leaked backup-encryption key alone can't decrypt these).
-- "connected" only flips true after a live grant-token call against
-- bKash's API actually succeeds (see bkashGateway.js) — submitting the
-- form alone does not set it.
create table if not exists institution_payment_gateways (
  id integer generated by default as identity primary key,
  provider text not null default 'bkash',
  "appKeyEnc" text,
  "appSecretEnc" text,
  "usernameEnc" text,
  "passwordEnc" text,
  connected boolean not null default false,
  "lastCheckedAt" text,
  "lastError" text,
  "updatedAt" text not null
);

-- ============================================================
-- BUSINESS_READINESS_ROADMAP.md Phase 8F — bKash create/execute lifecycle
-- ============================================================
-- One row per bKash checkout attempt started via the institution's own
-- connected gateway (institution_payment_gateways above). bKash's own
-- "Create Payment" call returns a paymentID and a checkout URL; the
-- guardian's browser (or, for an sms-topup, the admin's browser) is
-- redirected there, then bKash redirects back to our frontend with that
-- same paymentID — at which point our server calls bKash's "Execute
-- Payment" API and finalizes based on ITS response, never the redirect's
-- query params alone (those aren't signed, so trusting them directly
-- would let anyone fake a successful payment by hand-crafting the
-- callback URL). This row is what makes execute idempotent: once
-- status='completed', a second execute call for the same paymentID is a
-- no-op instead of double-crediting.
-- purpose distinguishes the two things Phase 8F reuses the same connected
-- gateway for: 'fee' (guardianId/studentId set, amount reduces that
-- student's due) vs 'sms-topup' (both null, amount credits sms_wallets —
-- the admin, not a guardian, is completing the checkout).
create table if not exists bkash_payment_intents (
  id integer generated by default as identity primary key,
  "paymentId" text,
  purpose text not null default 'fee',
  "guardianId" integer references guardian_accounts(id) on delete set null,
  "studentId" integer references students(id) on delete set null,
  amount integer not null,
  status text not null default 'initiated',
  "bkashTrxId" text,
  "createdAt" text not null,
  "completedAt" text
);

create unique index if not exists bkash_payment_intents_payment_id_unique
  on bkash_payment_intents ("paymentId") where "paymentId" is not null;

