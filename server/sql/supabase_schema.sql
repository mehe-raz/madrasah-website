create table if not exists students (
  id integer generated by default as identity primary key,
  name text not null,
  "nameEn" text default '',
  roll text not null,
  class text default '',
  dept text default 'হিফজ',
  type text default 'আবাসিক',
  fee integer default 1500,
  due integer default 0,
  phone text default '',
  blood text default 'O+',
  para integer default 0,
  status text default 'সক্রিয়'
);

create table if not exists attendance (
  id integer generated by default as identity primary key,
  "studentId" integer not null references students(id) on delete cascade,
  date text not null,
  status text not null,
  unique ("studentId", date)
);

create table if not exists payments (
  id integer generated by default as identity primary key,
  "studentId" integer not null references students(id) on delete cascade,
  student text not null,
  roll text not null,
  amount integer not null,
  date text not null,
  receipt text not null,
  method text default 'Cash',
  status text default 'Completed'
);

create table if not exists income (
  id integer generated by default as identity primary key,
  category text not null,
  amount integer not null,
  date text not null,
  note text default '',
  method text default 'Cash',
  receipt text not null,
  "studentId" integer references students(id) on delete set null,
  status text default 'Completed'
);

create table if not exists expenses (
  id integer generated by default as identity primary key,
  cat text not null,
  amount integer not null,
  date text not null,
  note text default ''
);

create table if not exists hifz_logs (
  id integer generated by default as identity primary key,
  "studentId" integer not null references students(id) on delete cascade,
  date text not null,
  sabaq text default ''
);

create table if not exists settings (
  key text primary key,
  value text not null
);

create table if not exists users (
  id integer generated by default as identity primary key,
  name text not null,
  role text not null default 'Teacher',
  email text unique,
  "passwordHash" text,
  "isProtected" integer default 0
);

create table if not exists password_resets (
  id integer generated by default as identity primary key,
  "userId" integer not null references users(id) on delete cascade,
  token text not null unique,
  "expiresAt" text not null
);

create table if not exists delete_requests (
  id integer generated by default as identity primary key,
  "entityType" text not null,
  "entityId" integer not null,
  label text not null,
  amount integer default 0,
  "requestedBy" integer,
  "requestedByName" text default '',
  status text not null default 'pending',
  "createdAt" text not null,
  "resolvedAt" text,
  "resolvedBy" integer,
  payload text default ''
);

create unique index if not exists delete_requests_pending_unique
on delete_requests ("entityType", "entityId", status)
where status = 'pending';

