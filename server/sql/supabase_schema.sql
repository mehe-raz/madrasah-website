-- Offline-first foundation (Phase 0): lets the idempotency middleware
-- (server/src/middleware/idempotency.js) recognize a retried mutation —
-- e.g. a payment or admission submitted while offline, queued client-side,
-- and resent once the connection returns — as the SAME request rather than
-- creating a duplicate. clientRequestId is generated in the browser (see
-- client/src/lib/api.ts) and sent as the X-Client-Request-Id header.
create table if not exists sync_requests (
  "clientRequestId" text primary key,
  route text not null,
  "statusCode" integer not null,
  response jsonb default '{}'::jsonb,
  "createdAt" text not null
);

