-- Exam results. "class"/"roll"/"studentName" are stored as a snapshot at
-- save time (same denormalization pattern as payments.student/payments.roll
-- above) so a result stays correct even if a student later changes class or
-- is edited. "published" gates public visibility: staff can enter and
-- correct marks freely, and results only become visible on the public
-- Result Lookup page once explicitly published.
create table if not exists results (
  id integer generated by default as identity primary key,
  "studentId" integer not null references students(id) on delete cascade,
  "examName" text not null,
  year text not null,
  class text not null,
  roll text not null,
  "studentName" text not null,
  subjects jsonb not null default '[]',
  "totalMarks" integer default 0,
  "obtainedMarks" integer default 0,
  gpa text default '',
  grade text default '',
  published integer default 0,
  "updatedAt" timestamptz default now(),
  unique ("studentId", "examName", year)
);

create index if not exists results_lookup_idx on results (class, roll, "examName", published);

