-- In-app notification center. A row is either targeted at specific roles
-- (targetRoles, e.g. new admission -> ["Admin","Super Admin"]) or at one
-- specific user (targetUserId, e.g. "your delete request was approved").
-- Read state is tracked per-user in notification_reads rather than a single
-- boolean on this table, since the same role-targeted notification can be
-- read by one Admin and still unread for another.
create table if not exists notifications (
  id integer generated by default as identity primary key,
  type text not null,
  title text not null,
  body text default '',
  "entityType" text default '',
  "entityId" integer,
  link text default '',
  "targetRoles" text[] not null default '{}',
  "targetUserId" integer references users(id) on delete cascade,
  "createdAt" text not null
);

create index if not exists notifications_created_at_idx on notifications ("createdAt" desc);

create table if not exists notification_reads (
  "notificationId" integer not null references notifications(id) on delete cascade,
  "userId" integer not null references users(id) on delete cascade,
  "readAt" text not null,
  primary key ("notificationId", "userId")
);
